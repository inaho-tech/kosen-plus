    /**
     * Get the latest version entry.
     */
    val latest: VersionEntry get() = entries.first()

    /**
     * Get changes since a specific version (exclusive).
     * Returns entries newer than the given version.
     */
    fun changesSince(lastSeenVersion: String): List<VersionEntry> {
        if (lastSeenVersion.isBlank()) return listOf(entries.first())
        val lastSeenIndex = entries.indexOfFirst { it.version == lastSeenVersion }
        return if (lastSeenIndex <= 0) {
            // Unknown version or already latest → show only latest
            listOf(entries.first())
        } else {
            entries.subList(0, lastSeenIndex)
        }
    }
